function HelpCard({ section }: { section: HelpSection }) {
  return (
    <Card withBorder radius="md" p="lg">
      <Stack gap="sm">
        <Group align="flex-start" gap="sm">
          <ThemeIcon variant="light" color={section.color} radius="md" size={34}>
            {section.icon}
          </ThemeIcon>
          <Stack gap={2}>
            <Title order={4}>{section.title}</Title>
            <Text size="sm" c="dimmed">
              {section.description}
            </Text>
          </Stack>
        </Group>
        <List spacing="xs" size="sm" icon={<IconCircleCheck size={16} />}>
          {section.items.map((item) => (
            <List.Item key={item}>{item}</List.Item>
          ))}
        </List>
      </Stack>
    </Card>
  );
}

export function HelpPage() {
  const me = useQuery({ queryKey: ["me"], queryFn: meRequest });

  if (me.isPending) {
    return <Text c="dimmed">Загрузка…</Text>;
  }
  if (me.isError) {
    return <Text c="red">{me.error instanceof Error ? me.error.message : "Ошибка"}</Text>;
  }

  const role = me.data.user.role;
  const sections = roleHelp[role];

  return (
    <Stack gap="lg">
      <Group justify="space-between" align="flex-start">
        <Stack gap={4}>
          <Group gap="xs">
            <IconBook2 size={28} stroke={1.5} />
            <Title order={3}>Инструкция</Title>
          </Group>
          <Text c="dimmed" maw={860}>
            ERM — сервис для управления заказами на фасады: от создания заказа и расчёта до прохождения этапов
            производства, раскроя, учёта трудозатрат, отчётов и клиентского просмотра статуса.
          </Text>
        </Stack>
        <Badge variant="light" size="lg">
          {roleLabels[role]}
        </Badge>
      </Group>

      <Alert color="blue" variant="light" icon={<IconShieldCheck size={18} />}>
        {roleSummaries[role]}
      </Alert>

      <SimpleGrid cols={{ base: 1, lg: 2 }} spacing="lg">
        {sections.map((section) => (
          <HelpCard key={section.title} section={section} />
        ))}
      </SimpleGrid>

      <Card withBorder radius="md" p="lg">
        <Group align="flex-start" gap="sm">
          <ThemeIcon variant="light" color="gray" radius="md" size={34}>
            <IconUsers size={18} />
          </ThemeIcon>
          <Stack gap={4}>
            <Title order={4}>Как устроены роли</Title>
            <Text size="sm" c="dimmed">
              Администратор управляет системой и данными, работник ведёт производство, заказчик отслеживает свои
              заказы. Пункты меню и действия скрываются по роли, а сервер дополнительно проверяет права при каждом
              запросе.
            </Text>
          </Stack>
        </Group>
      </Card>
    </Stack>
  );
}
